# Registry: every module in engineering_sim/science/mech/ (except core/ui helpers) that defines SECTION + CALCS
# ---------------------------------------------------------------------------------------------------
_REGISTRY = None
_SKIP_MODULES = {'core', 'charts', 'common', 'oracles'}


def registry():
    """{'sections': {key: Section}, 'calcs': {id: Calc}}; loaded once per process, sorted by order."""
    global _REGISTRY
    if _REGISTRY is not None:
        return _REGISTRY
    pkg = importlib.import_module('engineering_sim.science.mech')
    sections, calcs, errors = {}, {}, {}
    for info in sorted(pkgutil.iter_modules(pkg.__path__), key=lambda i: i.name):
        if info.name in _SKIP_MODULES or info.name.startswith('_'):
            continue
        try:
            mod = importlib.import_module(f'engineering_sim.science.mech.{info.name}')
        except Exception as exc:  # a broken section must not take the others down
            errors[info.name] = f'{type(exc).__name__}: {exc}'
            continue
        sec = getattr(mod, 'SECTION', None)
        if sec is None:
            continue
        if sec.key != info.name:
            errors[info.name] = f'SECTION key {sec.key!r} must equal module name'
            continue
        sections[sec.key] = sec
        for c in getattr(mod, 'CALCS', []):
            c.section = sec.key
            if c.id in calcs:
                errors[info.name] = f'duplicate calculator id {c.id}'
                continue
            calcs[c.id] = c
    _REGISTRY = {'sections': dict(sorted(sections.items(), key=lambda kv: (kv[1].order, kv[0]))),
                 'calcs': calcs, 'errors': errors}
    return _REGISTRY


def get(calc_id):
    c = registry()['calcs'].get(calc_id)
    if c is None:
        raise MechError(f'Unknown calculator: {calc_id!r}')
    return c


