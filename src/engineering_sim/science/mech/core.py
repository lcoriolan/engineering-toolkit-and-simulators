def _dimensionless_special(name):
    """Stand-in for a special function during the dimension check: argument must be dimensionless."""
    def fn(x):
        q = x if isinstance(x, pint.Quantity) else Q_(x)
        if not q.dimensionless:
            raise pint.errors.DimensionalityError(q.units, 'dimensionless', extra_msg=f' in {name}()')
        return Q_(1.0)
    return fn


_DIMLESS_SPECIALS = {n: _dimensionless_special(n) for n in ('gamma', 'erf', 'erfc')}


def dimension_check(calc):
    """Return a list of problems (empty = consistent). Equation calcs only.

    Each variable is replaced by a pint Quantity of its declared unit (magnitude 1.37 to keep log/asin
    arguments in-domain for most relations) and both sides of every equation are evaluated. pint raises
    on adding incompatible terms or passing a dimensioned value to exp/log/sin; the two sides must then
    share one dimensionality.
    """
    problems = []
    if calc.procedure is not None:
        return problems
    syms = symbols(calc)
    order = [syms[n] for n in calc.names]
    # Distinct, irrational-ish magnitudes per variable so differences such as r_o² − r_i² never vanish.
    vals = [Q_(0.37 * (1.0 + 0.6180339887 * ((k * 7) % 11) / 11), unit_of(calc.var(n).unit))
            for k, n in enumerate(calc.names)]
    for text, eq in zip(calc.equations, parsed(calc)):
        unused = {s.name for s in eq.free_symbols} - set(calc.names)
        if unused:
            problems.append(f'{text}: undeclared symbols {sorted(unused)}')
            continue
        try:
            with np.errstate(all='ignore'):
                sides = [sp.lambdify(order, side, modules=[_DIMLESS_SPECIALS, 'numpy'])(*vals)
                         for side in (eq.lhs, eq.rhs)]
            dims = [s.dimensionality if hasattr(s, 'dimensionality') else UREG.dimensionless.dimensionality
                    for s in sides]
            if dims[0] != dims[1]:
                problems.append(f'{text}: lhs {dims[0]} != rhs {dims[1]}')
        except pint.errors.DimensionalityError as exc:
            problems.append(f'{text}: {exc}')
        except Exception as exc:  # e.g. Piecewise not supported by pint; report so the author decides
            problems.append(f'{text}: could not evaluate with units ({type(exc).__name__}: {exc})')
    declared = set(calc.names)
    used = set()
    for eq in parsed(calc):
        used |= {s.name for s in eq.free_symbols}
    if declared - used:
        problems.append(f'declared but unused variables {sorted(declared - used)}')
    return problems


