_NUM_UNIT = re.compile(r'^\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)\s*(.*?)\s*$')


def unit_of(u):
    """pint Unit for a declared unit string ('' -> dimensionless)."""
    return UREG.Unit(u) if u else UREG.dimensionless


def dim_key(u):
    return str(unit_of(u).dimensionality) if u else ''


ANGULAR_SUGGESTIONS = {'radian': ['rad', 'deg', 'turn'], 'radian / second': ['rad/s', 'rpm', 'rps', 'deg/s'],
                       'radian / second ** 2': ['rad/s^2', 'rpm/s', 'deg/s^2']}


def suggestions(u):
    if u and _radian_power(u):
        key = str(Q_(1.0, u).to_root_units().units)
        return ANGULAR_SUGGESTIONS.get(key, [u])
    return UNIT_SUGGESTIONS.get(dim_key(u), [u] if u else [''])


def to_si(raw, var):
    """Convert user input (number | '12 kN' | {'value','unit'}) to a float in var.unit.

    A bare number is taken to be in the declared unit. Offset temperatures ('20 degC') are handled by
    building the Quantity from (magnitude, unit) rather than multiplying, which pint forbids.
    """
    if var.kind == 'text':
        if not isinstance(raw, str) or not raw.strip():
            raise MechError(f'{var.name}: expected text')
        raw = raw.strip()
        if var.choices and raw not in var.choices:
            raise MechError(f'{var.name}: {raw!r} is not one of {", ".join(map(str, var.choices))}')
        return raw
    if var.kind == 'json':
        if isinstance(raw, str):
            try:
                raw = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise MechError(f'{var.name}: expected JSON ({exc})')
        if not isinstance(raw, (list, dict)):
            raise MechError(f'{var.name}: expected a JSON list or object')
        return raw
    if isinstance(raw, dict):
        mag, unit = raw.get('value'), raw.get('unit') or var.unit
    elif isinstance(raw, (int, float)) and not isinstance(raw, bool):
        mag, unit = raw, var.unit
    elif isinstance(raw, str):
        m = _NUM_UNIT.match(raw)
        if not m:
            raise MechError(f'{var.name}: cannot read {raw!r}; use e.g. "12 kN"')
        mag, unit = m.group(1), m.group(2) or var.unit
    else:
        raise MechError(f'{var.name}: unsupported input {raw!r}')
    try:
        mag = float(mag)
    except (TypeError, ValueError):
        raise MechError(f'{var.name}: {mag!r} is not a number')
    if not math.isfinite(mag):
        raise MechError(f'{var.name}: value must be finite')
    unit = {'%': 'percent'}.get(unit, unit)
    try:
        q = Q_(mag, unit or 'dimensionless')
        _check_angle_content(q, var)
        return float(q.to(unit_of(var.unit)).magnitude)
    except MechError:
        raise
    except (pint.errors.UndefinedUnitError, pint.errors.DimensionalityError, AttributeError, ValueError) as exc:
        raise MechError(f'{var.name}: unit {unit!r} is not compatible with {var.unit or "dimensionless"} ({exc})')


def _radian_power(unit_or_q):
    """Exponent of radian in the root units (rpm → rad/s has 1; Hz → 1/s has 0)."""
    q = unit_or_q if isinstance(unit_or_q, pint.Quantity) else Q_(1.0, unit_or_q or 'dimensionless')
    return dict(q.to_root_units()._units).get('radian', 0)


def _check_angle_content(q, var):
    """Reject cyclic ↔ angular mix-ups that pint would silently convert with a 2π error.

    pint defines revolution = 2π rad and treats rad as dimensionless, so '1500 rpm' → 157 1/s and
    '1 Hz' → 1 rad/s. mechcalc therefore requires angular quantities (ω, θ) to be declared in rad-based
    units and cyclic ones (f, n in Hz or 1/s) not to be, and refuses inputs whose radian content differs.
    """
    if var.unit == '' and _radian_power(q) == 0:
        return
    if _radian_power(q) != _radian_power(var.unit):
        want = 'an angular unit (rad/s, rpm, rps, deg/s)' if _radian_power(var.unit) else \
            'a cyclic unit (Hz, 1/s, 1/min) — convert rpm with n = rpm/60'
        raise MechError(f'{var.name}: {q.units:~P} mixes angular and cyclic measure; use {want}')


def from_si(value, var, unit):
    """Convert an SI float to the requested display unit (returns value, unit)."""
    if not unit or unit == var.unit:
        return value, var.unit
    try:
        _check_angle_content(Q_(1.0, unit), var)
        return float(Q_(value, unit_of(var.unit)).to(unit).magnitude), unit
    except MechError:
        raise
    except Exception as exc:
        raise MechError(f'{var.name}: cannot express result in {unit!r} ({exc})')


# ---------------------------------------------------------------------------------------------------
# Symbolic layer (cached per process)
# ---------------------------------------------------------------------------------------------------
_SYM_CACHE = {}
# scipy first so special functions sympy may return (LambertW → scipy.special.lambertw, erf, gamma) evaluate;
# numpy covers the rest.
_LAMBDIFY_MODULES = ['scipy', 'numpy']


def _ck(calc):
    """Cache key: id plus object identity, so two declarations sharing an id never share symbols."""
    return (calc.id, id(calc))


def symbols(calc):
    """{name: sympy Symbol}; real symbols, positive when the variable cannot be negative."""
    key = ('syms', _ck(calc))
    if key not in _SYM_CACHE:
        out = {}
        for v in calc.vars:
            lo, _ = v.bounds()
            # positive=None (not False) for signed variables: sympy reads positive=False as "x <= 0", which
            # evaluates Eq(x, positive_expr) to False and silently drops positive roots.
            out[v.name] = sp.Symbol(v.name, real=True, positive=True if (lo is not None and lo >= 0) else None)
        _SYM_CACHE[key] = out
    return _SYM_CACHE[key]


def parsed(calc):
    """List of sympy Eq objects for an equation calculator (cached)."""
    key = ('eqs', _ck(calc))
    if key not in _SYM_CACHE:
        syms = symbols(calc)
        local = dict(SYMPY_FUNCS)
        local.update(syms)
        eqs = []
        for text in calc.equations:
            if text.count('=') != 1:
                raise MechError(f'{calc.id}: equation must contain exactly one "=": {text!r}')
            lhs, rhs = text.split('=')
            try:
                eqs.append(sp.Eq(sp.sympify(lhs, locals=local), sp.sympify(rhs, locals=local)))
            except (sp.SympifyError, SyntaxError, TypeError) as exc:
                raise MechError(f'{calc.id}: cannot parse {text!r}: {exc}')
        _SYM_CACHE[key] = eqs
    return _SYM_CACHE[key]


class _Timeout(Exception):
    pass


@contextmanager
def time_limit(seconds):
    """SIGALRM guard around sympy.solve, which can run unboundedly on transcendental systems.

    Only effective in the main thread (worker and unittest both qualify); elsewhere it is a no-op.
    """
    def _raise(signum, frame):
        raise _Timeout()
    try:
        old = signal.signal(signal.SIGALRM, _raise)
    except ValueError:  # not main thread
        yield
        return
    signal.setitimer(signal.ITIMER_REAL, seconds)
    try:
        yield
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)


def general_solution(calc, unknowns):
    """Closed-form solutions for ``unknowns`` in terms of the other variables, or None.

    Returns a list of dicts {unknown: lambdified function(*known_values)} plus the ordered known names.
    Cached; a timeout or NotImplementedError caches None so numeric fallback is used immediately.
    """
    key = ('gen', _ck(calc), tuple(unknowns))
    if key in _SYM_CACHE:
        return _SYM_CACHE[key]
    if os.environ.get('MECH_NUMERIC_ONLY'):
        # Test hook: exercise the numeric fallback that a symbolic timeout would take under load.
        _SYM_CACHE[key] = None
        return None
    syms = symbols(calc)
    eqs = parsed(calc)
    unk = [syms[u] for u in unknowns]
    known = [n for n in calc.names if n not in unknowns]
    result = None
    try:
        with time_limit(1.5):
            sols = sp.solve(eqs, unk, dict=True)
        if sols:
            result = []
            for s in sols:
                if not all(u in s for u in unk):
                    continue
                result.append({u.name: sp.lambdify([syms[k] for k in known], s[u], modules=_LAMBDIFY_MODULES)
                               for u in unk})
            result = (result, known) if result else None
    except (_Timeout, NotImplementedError, TypeError, ValueError, AttributeError):
        result = None
    _SYM_CACHE[key] = result
    return result


def _abs_terms(expr):
    """Cancellation-free magnitude of an expression: every sum becomes a sum of absolute values.

    Used only to scale residuals: when terms cancel to (near) zero — a radial stress at a free edge, a
    holding force exactly at the friction limit — round-off is judged against the size of the cancelling
    terms instead of against zero. Functions such as exp/cos keep their arguments unchanged.
    """
    expr = expr.replace(lambda e: e.is_Add, lambda e: sp.Add(*[sp.Abs(a) for a in e.args]))
    # Bounded oscillating factors are sized by their bound: sin(x) at x ≈ kπ is ~1e-16 of round-off, which would
    # otherwise shrink the residual scale to noise (review of brief 21: solar declination at the equinox).
    return expr.replace(lambda e: isinstance(e, (sp.sin, sp.cos)), lambda e: sp.Integer(1))


def residual_fn(calc):
    """Signed, scale-free residuals: f(values dict) -> [(lhs - rhs) / scale, ...].

    scale = max(|lhs|, |rhs|, 1e-6 · (|lhs|_terms + |rhs|_terms)); with the 1e-7 acceptance
    threshold a root must satisfy the equation to 1e-13 of its cancelling-term magnitude with |·|_terms from _abs_terms, so the
    residual is relative for ordinary values yet smooth and meaningful when a side is legitimately zero.
    """
    key = ('res', _ck(calc))
    if key not in _SYM_CACHE:
        syms = symbols(calc)
        order = [syms[n] for n in calc.names]
        fns = []
        for e in parsed(calc):
            fns.append((sp.lambdify(order, e.lhs, modules=_LAMBDIFY_MODULES),
                        sp.lambdify(order, e.rhs, modules=_LAMBDIFY_MODULES),
                        sp.lambdify(order, _abs_terms(e.lhs) + _abs_terms(e.rhs), modules=_LAMBDIFY_MODULES)))
        _SYM_CACHE[key] = fns
    fns = _SYM_CACHE[key]

    def f(values):
        args = [values[n] for n in calc.names]
        out = []
        for fl, fr, fm in fns:
            with np.errstate(all='ignore'):
                try:
                    a, b, m = complex(fl(*args)), complex(fr(*args)), complex(fm(*args))
                except (ZeroDivisionError, ValueError, TypeError, OverflowError):
                    out.append(float('nan'))
                    continue
            scale = max(abs(a), abs(b), 1e-6 * abs(m), 1e-300)
            d = (a - b) / scale
            out.append(d.real if abs(d.imag) <= 1e-12 else float('nan'))
        return out
    return f


