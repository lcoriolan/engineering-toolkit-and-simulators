@dataclass
class Var:
    """One calculator variable.

    name     identifier used in equations/procedures (ASCII, e.g. 'sigma_x', 'T1')
    unit     coherent SI pint unit string; '' for dimensionless
    desc     one-line meaning shown in the form
    lo, hi   admissible SI range (inclusive); roots outside are rejected; also brackets numeric solves
    label    display symbol (unicode), defaults to name
    integer  True for counts (teeth, coils); solved values are reported with a rounding warning
    signed   True when negative values are physical (moments, deflections); default False means >=0
             unless ``lo`` says otherwise
    source   optional cite record dict for a coefficient whose default is taken from a table
    kind     'scalar' (default), 'json' for structured procedure inputs (truss geometry, part lists) or
             'text' for a string such as a fluid name or end condition (optionally restricted to ``choices``);
             json/text values pass through unconverted (state SI units of json in ``desc``) and are never
             solved for
    """
    name: str
    unit: str = ''
    desc: str = ''
    lo: float | None = None
    hi: float | None = None
    label: str | None = None
    integer: bool = False
    signed: bool = False
    source: dict | None = None
    kind: str = 'scalar'
    choices: list | None = None

    @property
    def structured(self):
        """True for non-numeric inputs (json/text) that are passed through and never solved for."""
        return self.kind in ('json', 'text')

    def bounds(self):
        """(lo, hi) with the sign convention applied; None means unbounded on that side."""
        lo = self.lo if self.lo is not None else (None if self.signed else 0.0)
        return lo, self.hi


def V(name, unit='', desc='', **kw):
    """Shorthand constructor used by section modules: V('P', 'N', 'axial load')."""
    return Var(name, unit, desc, **kw)


@dataclass
class Calc:
    """One calculator. Exactly one of ``equations`` / ``procedure`` is set.

    key          short id inside the section ('belt_friction'); full id is '<section>.<key>'
    title        human title
    vars         list[Var] covering every symbol used
    outputs      default unknowns (equation calcs) or produced values (procedures)
    equations    list of 'lhs = rhs' strings
    procedure    callable(dict name->float SI) -> dict name->float (or list/dict structures)
    example      dict name->SI float for every non-output variable (physically sensible case)
    assumptions  list of strings (validity limits the user must know)
    refs         list of strings: standard textbook relation names / standards. Recalled references are
                 labelled as such; never invent page numbers.
    plots        list of plot specs: {'id','title','x','y':[...],'from','to','n','xlog','ylog'} for a generic
                 sweep, or {'id','title','fn': callable(values)->chart} for a custom diagram
    keywords     extra search terms
    no_invert    {var: reason} for variables that cannot be recovered (e.g. appears only inside a floor())
    """
    key: str
    title: str
    vars: list
    outputs: list
    equations: list = field(default_factory=list)
    procedure: Callable | None = None
    example: dict = field(default_factory=dict)
    assumptions: list = field(default_factory=list)
    refs: list = field(default_factory=list)
    plots: list = field(default_factory=list)
    keywords: list = field(default_factory=list)
    no_invert: dict = field(default_factory=dict)
    section: str = ''

    @property
    def id(self):
        return f'{self.section}.{self.key}'

    def var(self, name):
        for v in self.vars:
            if v.name == name:
                return v
        raise MechError(f'{self.id}: no variable named {name!r}')

    @property
    def names(self):
        return [v.name for v in self.vars]


