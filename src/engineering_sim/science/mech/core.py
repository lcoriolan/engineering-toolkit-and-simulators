def _admissible(calc, name, x):
    v = calc.var(name)
    if v.structured or not isinstance(x, (int, float)):
        return True
    lo, hi = v.bounds()
    tol = 1e-9 * max(1.0, abs(x))
    return (lo is None or x >= lo - tol) and (hi is None or x <= hi + tol)


def _real(x):
    """Real float from a numpy/sympy/complex scalar, or None when genuinely complex/non-finite."""
    try:
        z = complex(x)
    except (TypeError, ValueError):
        return None
    if not (math.isfinite(z.real) and math.isfinite(z.imag)):
        return None
    if abs(z.imag) > 1e-9 * max(1.0, abs(z.real)):
        return None
    return z.real


def _scan_grid(calc, name, hint=None):
    """Candidate abscissae for a 1-D root scan inside the variable's admissible range."""
    v = calc.var(name)
    lo, hi = v.bounds()
    pos = np.logspace(-12, 12, 481)
    pts = []
    if lo is not None and hi is not None:
        pts.extend(np.linspace(lo, hi, 801))
        if lo >= 0:
            pts.extend(pos[(pos >= lo) & (pos <= hi)])
    else:
        pts.extend(pos if hi is None else pos[pos <= hi])
        if lo is None or lo < 0:
            neg = -pos
            pts.extend(neg if lo is None else neg[neg >= lo])
        if lo is not None and lo > 0:
            pts = [p for p in pts if p >= lo]
        pts.append(0.0 if (lo is None or lo <= 0) else lo)
    if hint:
        pts.extend([hint * k for k in (0.5, 0.9, 1.0, 1.1, 2.0)])
    return np.unique(np.array([p for p in pts if (lo is None or p >= lo) and (hi is None or p <= hi)]))


def _numeric_1d(f, grid):
    """All sign-change roots of scalar f over grid, refined by brentq. f may return None (domain error)."""
    roots = []
    prev_x, prev_y = None, None
    for x in grid:
        y = f(x)
        if y is None or not math.isfinite(y):
            prev_x, prev_y = None, None
            continue
        if y == 0.0:
            roots.append(float(x))
        elif prev_y is not None and prev_y * y < 0:
            try:
                roots.append(optimize.brentq(lambda t: f(t) if f(t) is not None else np.nan, prev_x, x,
                                             xtol=1e-15, rtol=1e-13, maxiter=200))
            except (ValueError, RuntimeError):
                pass
        prev_x, prev_y = x, y
    return roots


def _dedupe(solutions, names):
    out = []
    for s in solutions:
        if not any(all(math.isclose(s[n], o[n], rel_tol=1e-7, abs_tol=1e-12) for n in names) for o in out):
            out.append(s)
    return out


def solve_equations(calc, known, unknowns):
    """Solve an equation calculator. known: {name: SI float}; returns (solutions, method).

    solutions is a list of dicts over ``unknowns`` (admissible, verified by residual), sorted so the
    first is closest (log-distance) to the calculator's example values — a deterministic, physically
    typical choice when a relation has several roots (quadratics, inverse trig).
    """
    eqs = parsed(calc)
    if len(unknowns) != len(eqs):
        raise MechError(f'{calc.id}: {len(eqs)} equation(s) need exactly {len(eqs)} unknown(s); '
                        f'got {len(unknowns)} ({", ".join(unknowns) or "none"})')
    missing = [n for n in calc.names if n not in unknowns and n not in known]
    if missing:
        raise MechError(f'{calc.id}: missing input(s) {", ".join(missing)}')
    res = residual_fn(calc)
    candidates, method = [], 'symbolic'
    gen = general_solution(calc, unknowns)
    if gen:
        branches, known_order = gen
        args = [known[k] for k in known_order]
        for branch in branches:
            sol = {}
            with np.errstate(all='ignore'):
                for u, fn in branch.items():
                    try:
                        sol[u] = _real(fn(*args))
                    except (ZeroDivisionError, ValueError, TypeError, OverflowError, NameError):
                        sol[u] = None
            if all(x is not None for x in sol.values()):
                candidates.append(sol)
    if not candidates:
        method = 'numeric'
        candidates = _numeric_solve(calc, known, unknowns, res)
    good = []
    for s in candidates:
        if not all(_admissible(calc, u, s[u]) for u in unknowns):
            continue
        vals = dict(known)
        vals.update(s)
        if max(abs(r) if math.isfinite(r) else 1.0 for r in res(vals)) < 1e-7:
            good.append(s)
    good = _dedupe(good, unknowns)
    good.sort(key=lambda s: sum(_logdist(s[u], calc.example.get(u)) for u in unknowns))
    return good, method


def _logdist(x, ref):
    if ref is None or ref == 0 or x == 0 or (x > 0) != (ref > 0):
        return abs(x - (ref or 0.0)) * 1e-6 + (0 if ref is None else 1.0)
    return abs(math.log(abs(x) / abs(ref)))


def _numeric_solve(calc, known, unknowns, res):
    """Fallback solver. Sequential decomposition first: repeatedly take an equation with exactly one
    remaining unknown, find all its bracketed roots in 1-D and branch on each; any coupled remainder goes
    to bounded multi-start least squares. Branching keeps every admissible root, not just the first."""
    syms = symbols(calc)
    order = [syms[n] for n in calc.names]
    eqs = parsed(calc)
    fns = [sp.lambdify(order, e.lhs - e.rhs, modules=_LAMBDIFY_MODULES) for e in eqs]
    free = [{s.name for s in e.free_symbols} for e in eqs]

    def branch(vals, remaining_eqs, unk, depth=0):
        if not unk:
            return [{u: vals[u] for u in unknowns}]
        if depth > 12:
            return []
        pick = next((i for i in remaining_eqs if len(free[i] & set(unk)) == 1), None)
        if pick is None:
            sub_known = {k: v for k, v in vals.items() if k not in unk}
            found = _least_squares(res, calc, sub_known, unk)
            out = []
            for f_ in found:
                merged = dict(vals)
                merged.update(f_)
                out.append({u: merged[u] for u in unknowns})
            return out
        u = next(iter(free[pick] & set(unk)))

        def f(x, _vals=vals, _u=u, _fn=fns[pick]):
            v2 = dict(_vals)
            v2[_u] = x
            with np.errstate(all='ignore'):
                try:
                    return _real(_fn(*[v2.get(n, np.nan) for n in calc.names]))
                except (ZeroDivisionError, ValueError, TypeError, OverflowError):
                    return None
        out = []
        # Rank bracketed roots by closeness to the example before capping the branch count, so periodic
        # residuals (cos, tan) cannot push the physical root out of the kept set.
        roots = sorted(_numeric_1d(f, _scan_grid(calc, u, calc.example.get(u))),
                       key=lambda r, _u=u: _logdist(r, calc.example.get(_u)))
        for r in roots[:16]:
            v2 = dict(vals)
            v2[u] = r
            out.extend(branch(v2, [i for i in remaining_eqs if i != pick], [x for x in unk if x != u], depth + 1))
        return out

    start = dict(known)
    for u in unknowns:
        start.setdefault(u, np.nan)
    return branch(start, list(range(len(eqs))), list(unknowns))


def _least_squares(resid, calc, known, unknowns):
    """Bounded multi-start least squares on normalized residuals (coupled systems and procedures).

    Starts: the example values, then deterministic log-uniform spreads clipped into each variable's
    admissible range, so the optimiser never wanders into physically excluded regions.
    """
    rng = np.random.default_rng(12345)  # fixed seed: results must be reproducible
    lows, highs, base = [], [], []
    for u in unknowns:
        lo, hi = calc.var(u).bounds()
        lows.append(-np.inf if lo is None else lo)
        highs.append(np.inf if hi is None else hi)
        b = calc.example.get(u)
        if not isinstance(b, (int, float)) or b == 0:
            b = (lo + hi) / 2 if (lo is not None and hi is not None) else 1.0
        base.append(float(b))
    lows, highs = np.array(lows, float), np.array(highs, float)
    starts = [np.array(base)]
    for _ in range(24):
        x = np.array([b * 10 ** rng.uniform(-3, 3) * (rng.choice([-1, 1]) if calc.var(u).signed else 1)
                      for b, u in zip(base, unknowns)])
        starts.append(x)
    out = []
    span = np.where(np.isfinite(highs - lows), highs - lows, 0.0)
    for x0 in starts:
        with np.errstate(invalid='ignore'):  # inf bounds make lows + span*… NaN on unbounded sides; clip ignores it
            x0 = np.clip(x0, lows + 1e-9 * span, highs - 1e-9 * span)
            x0 = np.where(x0 == lows, np.where(np.isfinite(lows), lows + np.maximum(1e-9, 1e-6 * np.abs(lows)), x0), x0)

        def fun(x):
            vals = dict(known)
            vals.update(dict(zip(unknowns, map(float, x))))
            r = resid(vals)
            return [1e6 if (y is None or not math.isfinite(y)) else y for y in r]
        try:
            sol = optimize.least_squares(fun, x0, bounds=(lows, highs), xtol=1e-15, ftol=1e-15,
                                         gtol=1e-15, max_nfev=3000)
        except (ValueError, RuntimeError):
            continue
        if max(abs(y) for y in sol.fun) < 1e-9:
            out.append(dict(zip(unknowns, map(float, sol.x))))
    return out


def run_procedure(calc, known, unknowns):
    """Procedure calculators: forward when every unknown is an output; else numeric inversion.

    Inversion: the caller supplies target values for as many outputs as there are unknown inputs; the
    remaining outputs are then computed forward at the recovered inputs.
    """
    outputs = set(calc.outputs)
    unknown_inputs = [u for u in unknowns if u not in outputs]
    input_names = [n for n in calc.names if n not in outputs]
    if not unknown_inputs:
        missing = [n for n in input_names if n not in known]
        if missing:
            raise MechError(f'{calc.id}: missing input(s) {", ".join(missing)}')
        vals = {n: known[n] for n in input_names}
        try:
            return [calc.procedure(vals)], 'procedure'
        except MechError:
            raise
        except (OverflowError, ZeroDivisionError) as exc:  # numeric blow-ups are user-facing, not crashes
            raise MechError(f'{calc.id}: numeric overflow or division by zero ({exc})')
        except (IndexError, KeyError, TypeError, ValueError) as exc:
            # Malformed structured input (short json rows, non-numeric entries) must not surface as a raw Python
            # error on the web/CLI path (verify25f: fea rows [[0]], [2, -1]).
            raise MechError(f'{calc.id}: invalid input ({type(exc).__name__}: {exc})')
    targets = [o for o in calc.outputs if o in known and o not in unknowns]
    if len(targets) < len(unknown_inputs):
        raise MechError(f'{calc.id}: to solve for {", ".join(unknown_inputs)} give a target value for '
                        f'{len(unknown_inputs)} of the outputs ({", ".join(calc.outputs)})')
    targets = targets[:len(unknown_inputs)]
    missing = [n for n in input_names if n not in known and n not in unknown_inputs]
    if missing:
        raise MechError(f'{calc.id}: missing input(s) {", ".join(missing)}')

    def forward(x_vals):
        vals = {n: known[n] for n in input_names if n not in unknown_inputs}
        vals.update(x_vals)
        try:
            with np.errstate(all='ignore'):
                return calc.procedure(vals)
        except (MechError, ValueError, ZeroDivisionError, OverflowError, ArithmeticError):
            return None

    def resid(vals):
        out = forward({u: vals[u] for u in unknown_inputs})
        if out is None:
            return [None] * len(targets)
        r = []
        for t in targets:
            y = out.get(t)
            if not isinstance(y, (int, float)) or not math.isfinite(y):
                r.append(None)
                continue
            scale = max(abs(known[t]), abs(y), 1e-300)
            r.append((y - known[t]) / scale)
        return r

    if len(unknown_inputs) == 1:
        u = unknown_inputs[0]
        roots = _numeric_1d(lambda x: resid({u: x})[0], _scan_grid(calc, u, calc.example.get(u)))
        cands = [{u: r} for r in roots]
    else:
        cands = _least_squares(resid, calc, {}, unknown_inputs)
    sols = []
    for c in cands:
        if not all(_admissible(calc, u, c[u]) for u in unknown_inputs):
            continue
        out = forward(c)
        if out is None or any(abs(y) > 1e-7 for y in resid(c) if y is not None) or None in resid(c):
            continue
        full = dict(out)
        full.update(c)
        sols.append(full)
    sols = _dedupe(sols, unknown_inputs)
    sols.sort(key=lambda s: sum(_logdist(s[u], calc.example.get(u)) for u in unknown_inputs))
    return sols, 'numeric inversion'


