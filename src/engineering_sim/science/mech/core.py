def example_solution(calc):
    """Full SI assignment of every variable at the calculator's example (forward solve)."""
    sols = (run_procedure(calc, dict(calc.example), list(calc.outputs))[0] if calc.procedure
            else solve_equations(calc, dict(calc.example), list(calc.outputs))[0])
    if not sols:
        raise MechError(f'{calc.id}: example has no admissible forward solution')
    full = dict(calc.example)
    full.update(sols[0])
    return full


def roundtrip(calc, rel_tol=1e-6):
    """Recover every invertible variable from the others at the example point.

    Equation calcs: for each variable v, try unknown sets formed by swapping v in for one output; the
    check passes when the original value is among the admissible roots. Procedures: each scalar input
    is recovered against one scalar output target. Returns {var: 'ok' | 'skipped: reason' | 'FAIL: ...'}.
    """
    full = example_solution(calc)
    report = {}
    outputs = list(calc.outputs)
    for v in calc.vars:
        name = v.name
        if name in calc.no_invert:
            report[name] = 'skipped: ' + calc.no_invert[name]
            continue
        if name in outputs:
            report[name] = 'ok (forward)'
            continue
        if v.structured:
            report[name] = 'skipped: structured input'
            continue
        ok, last = False, 'no admissible root'
        if calc.procedure is None:
            trials = [[name] + [o for o in outputs if o != drop] for drop in outputs]
        else:
            trials = [[name] for o in outputs if isinstance(full.get(o), (int, float))][:1]
        for unk in trials:
            known = {k: val for k, val in full.items() if k not in unk and k in calc.names
                     and (isinstance(val, (int, float)) or calc.var(k).structured)
                     and not (k in outputs and calc.var(k).structured)}
            try:
                if calc.procedure is None:
                    sols, _ = solve_equations(calc, known, unk)
                else:
                    sols, _ = run_procedure(calc, known, unk)
            except MechError as exc:
                last = str(exc)
                continue
            if any(math.isclose(s[name], full[name], rel_tol=rel_tol, abs_tol=1e-12) for s in sols):
                ok = True
                break
            if sols:
                last = f'roots {[s[name] for s in sols][:4]} != {full[name]}'
        report[name] = 'ok' if ok else 'FAIL: ' + last
    return report
