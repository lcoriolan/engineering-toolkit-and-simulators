# DESCRIPTION: Declarative mechanical-engineering calculator core. A calculator declares its
#              variables (with SI units and admissible ranges) plus either residual equations
#              or a numeric procedure; this module supplies unit parsing, the dimensional
#              consistency gate, solve-for-any-variable, parameter sweeps and chart specs.
"""mechcalc core: one registry, generic solve/sweep/plot, no per-calculator plumbing.

Conventions (read before writing a section module):
- Every Var.unit is a *coherent SI* pint unit string ('N', 'm', 'Pa', 'm^4', 'W', 'K', 'rad', '' for
  dimensionless). All arithmetic happens in those units; users may enter any compatible unit
  ('12 kN', '3 in', '20 degC') and ask for results in any compatible unit.
- Angles are radians internally (pint treats rad as dimensionless, so 'deg' input converts).
- Absolute temperature is K. A temperature *difference* must use unit 'delta_degC' or 'K' and be
  entered as 'delta_degC'/'K'; a plain 'degC' input is an absolute temperature (offset applied).
- Equation calculators: ``equations`` are strings 'lhs = rhs' over the Var names. Any variable can be
  the unknown: with n equations the caller supplies all but n variables. Symbolic solving (sympy) is
  tried first under a time limit; bracketed numeric root-finding is the fallback.
- Procedure calculators: ``procedure(values) -> dict`` for things that are not closed-form (iterative
  friction factor, truss assembly, cycles). Outputs listed in ``outputs``; scalar inputs can still be
  solved for by numeric inversion against one given output value.
- Every calculator carries an ``example`` (inputs that make a physically sensible case). The test
  suite uses it for the dimensional check and the inversion round trip; numeric *oracles* live
  separately in tests/fixtures/mech_oracles/<section>.json and must never be generated by this code.

Heavy imports (sympy, pint, numpy, scipy) are module-level here: this package only runs inside the
configured science environment worker, never under the standard-library studio interpreter (see ops_mech.py).
"""
