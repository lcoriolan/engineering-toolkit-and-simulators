def _numeric_bits(x):
    """Approximate size in bits of an exact sympy number (0 for floats/symbolic), without evaluating powers."""
    try:
        if x.is_Integer:
            return int(x).bit_length()
        if x.is_Rational:
            return max(int(x.p).bit_length(), int(x.q).bit_length())
    except (TypeError, ValueError, AttributeError):
        pass
    return 0


def safe_expr(text, variables=(), max_len=2000, max_exponent=1000):
    """Build a sympy expression from user text WITHOUT evaluating any Python.

    The text is parsed with ``ast.parse(mode='eval')`` and only these nodes are accepted: numeric constants,
    names (declared ``variables``, allow-listed constants), + − × ÷ ** % and unary ±, ``^`` (rewritten to **)
    and calls of allow-listed function names with positional arguments. Attribute access, subscripts,
    lambdas, comprehensions, strings, keywords and every other node raise MechError, so payloads such as
    ``().__class__.__mro__`` cannot run. Constant exponents above ``max_exponent`` are refused (DoS guard).
    Returns (expr, {name: Symbol}) with real symbols for the declared variables.
    """
    import ast
    if not isinstance(text, str) or not text.strip():
        raise MechError('expression is empty')
    if len(text) > max_len:
        raise MechError(f'expression longer than {max_len} characters')
    syms = {}
    for name in variables:
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', str(name)) or name.startswith('__'):
            raise MechError(f'invalid variable name {name!r}')
        syms[name] = sp.Symbol(name, real=True)
    # '^' means power to engineers; rewrite it textually BEFORE parsing so it gets ** precedence (as an AST
    # BitXor it would bind looser than + and −). Safe because string literals are rejected below.
    try:
        tree = ast.parse(text.strip().replace('^', '**'), mode='eval')
    except SyntaxError as exc:
        raise MechError(f'cannot parse expression: {exc.msg}')
    binops = {ast.Add: lambda a, b: a + b, ast.Sub: lambda a, b: a - b, ast.Mult: lambda a, b: a * b,
              ast.Div: lambda a, b: a / b, ast.Pow: lambda a, b: a ** b,
              ast.Mod: lambda a, b: sp.Mod(a, b)}

    def build(node):
        if isinstance(node, ast.Expression):
            return build(node.body)
        if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)) and not isinstance(node.value, bool):
            if isinstance(node.value, int) and node.value.bit_length() > _SAFE_MAX_BITS:
                raise MechError('numeric constant too large')
            return sp.Float(node.value) if isinstance(node.value, float) else sp.Integer(node.value)
        if isinstance(node, ast.Name):
            if node.id in syms:
                return syms[node.id]
            if node.id in _SAFE_CONSTS:
                return _SAFE_CONSTS[node.id]
            raise MechError(f'unknown name {node.id!r} (declare it as a variable)')
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
            v = build(node.operand)
            return -v if isinstance(node.op, ast.USub) else v
        if isinstance(node, ast.BinOp) and type(node.op) in binops:
            left, right = build(node.left), build(node.right)
            if isinstance(node.op, ast.Pow) and right.is_number:
                if abs(complex(right)) > max_exponent:
                    raise MechError(f'exponent larger than {max_exponent}')
                # Nested constant powers pass the per-exponent check but explode in size, e.g.
                # ((10**1000)**1000)**1000 → 10**(10**9); estimate the result size before sympy computes it.
                bits = _numeric_bits(left)
                if bits and bits * abs(complex(right)) > _SAFE_MAX_BITS:
                    raise MechError('constant power result too large')
            if isinstance(node.op, (ast.Mult, ast.Add, ast.Sub)) and \
                    _numeric_bits(left) + _numeric_bits(right) > 2 * _SAFE_MAX_BITS:
                raise MechError('constant arithmetic result too large')
            return binops[type(node.op)](left, right)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in _SAFE_FUNCS \
                and not node.keywords and all(not isinstance(a, ast.Starred) for a in node.args):
            args = [build(a) for a in node.args]
            # sympy evaluates some functions of exact numbers eagerly (gamma(10**7) computes a 10⁷! factorial).
            for a in args:
                if a.is_number and (_numeric_bits(a) > 64 or
                                    (a.is_real and abs(float(a)) > _SAFE_MAX_SPECIAL_ARG and
                                     node.func.id in ('gamma', 'erf', 'erfc', 'floor', 'ceiling'))):
                    raise MechError(f'argument of {node.func.id}() too large')
            return _SAFE_FUNCS[node.func.id](*args)
        raise MechError(f'expression element not allowed: {type(node).__name__}')

    # The whole construction runs under a wall-clock limit as a backstop for any eager evaluation not caught above.
    try:
        with time_limit(2.0):
            expr = build(tree)
    except _Timeout:
        raise MechError('expression took too long to parse')
    return expr, syms


