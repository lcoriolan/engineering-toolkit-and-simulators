def _clean(x):
    """JSON-safe structure: non-finite floats become None (the worker refuses NaN/inf)."""
    if isinstance(x, dict):
        return {k: _clean(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_clean(v) for v in x]
    if isinstance(x, (np.floating, float)):
        x = float(x)
        return x if math.isfinite(x) else None
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.ndarray):
        return _clean(x.tolist())
    return x


def parse_inputs(calc, raw_inputs, unknowns):
    """User inputs -> SI floats; unknown variables are ignored even if a value was sent."""
    known = {}
    for name, raw in (raw_inputs or {}).items():
        if name in unknowns or raw is None or raw == '':
            continue
        known[name] = to_si(raw, calc.var(name))
    return known


@_simulation_operation('science_bundle.mechanics.compute', kind='static')
def compute(calc_id, inputs=None, solve_for=None, out_units=None):
    """Solve one calculator and return the full provenance-carrying result dict."""
    calc = get(calc_id)
    unknowns = list(solve_for or calc.outputs)
    for u in unknowns:
        calc.var(u)
    known = parse_inputs(calc, inputs, unknowns)
    if calc.procedure is not None:
        sols, method = run_procedure(calc, known, unknowns)
    else:
        sols, method = solve_equations(calc, known, unknowns)
    if not sols:
        raise MechError(f'{calc.id}: no admissible solution for {", ".join(unknowns)} with these inputs '
                        '(check ranges and units)')
    return _format(calc, known, unknowns, sols, method, out_units or {})


def _format(calc, known, unknowns, sols, method, out_units):
    warnings = []
    # Procedures may attach user-facing caveats for this particular evaluation (e.g. a turbulent correlation
    # evaluated at Re < 2300) under the reserved key '_warnings'; they are surfaced, never treated as outputs.
    extra = sols[0].pop('_warnings', None) if isinstance(sols[0], dict) else None
    for s_ in sols[1:]:
        if isinstance(s_, dict):
            s_.pop('_warnings', None)
    if extra:
        warnings.extend(str(w) for w in (extra if isinstance(extra, (list, tuple)) else [extra]))
    method_name = f'mechcalc {calc.id} ({method})'
    results = {}
    primary = sols[0]
    for name, val in primary.items():
        if isinstance(val, (int, float, np.floating)) and not isinstance(val, bool):
            try:
                v = calc.var(name)
            except MechError:
                results[name] = cite.value(_clean(val), '', 'derived', method=method_name)
                continue
            shown, unit = from_si(float(val), v, out_units.get(name))
            if v.integer and not math.isclose(val, round(val), abs_tol=1e-6):
                warnings.append(f'{name} = {val:.4g} is not an integer; round to a feasible count and re-check')
            if not _admissible(calc, name, float(val)):
                warnings.append(f'{name} = {val:.6g} {v.unit} is outside its stated range')
            results[name] = cite.value(_clean(shown), unit, 'derived', method=method_name)
        else:
            results[name] = {'value': _clean(val), 'kind': 'derived', 'method': method_name, 'unit': ''}
    for name, val in known.items():
        v = calc.var(name)
        if v.structured:
            continue
        if v.integer and not math.isclose(val, round(val), abs_tol=1e-9):
            warnings.append(f'input {name} = {val:.6g} should be an integer count')
        lo, hi = v.bounds()
        if (lo is not None and val < lo) or (hi is not None and val > hi):
            warnings.append(f'input {name} = {val:.6g} {v.unit} is outside its stated range '
                            f'[{lo if lo is not None else "-inf"}, {hi if hi is not None else "inf"}]')
    alternatives = []
    for s in sols[1:]:
        alternatives.append({u: _clean(s[u]) for u in unknowns if u in s})
    if alternatives:
        warnings.append(f'{len(sols)} admissible roots; the one closest to the typical example is shown')
    inputs = {n: cite.value(_clean(x), calc.var(n).unit, 'user') for n, x in known.items()}
    return _clean({
        'calc': calc.id, 'title': calc.title, 'section': calc.section, 'method': method,
        'unknowns': unknowns, 'inputs': inputs, 'results': results, 'alternatives': alternatives,
        'equations': equation_text(calc), 'assumptions': calc.assumptions, 'refs': calc.refs,
        'warnings': warnings,
    })


def equation_text(calc):
    """[{'text','latex'}] for display. Procedures show their declared relation summary in refs instead."""
    if calc.procedure is not None:
        return []
    return [{'text': t, 'latex': sp.latex(e)} for t, e in zip(calc.equations, parsed(calc))]


_NON_METRIC = {'in', 'ft', 'lbf', 'kip', 'psi', 'ksi', 'lb', 'mph', 'hp', 'Btu', 'lbf*ft', 'lbf*in', 'gpm', 'cfm',
               'lb/ft^3', 'ft/s', 'ft/s^2', 'in^2', 'ft^2', 'in^3', 'ft^3', 'in^4', 'lb*ft^2', 'lb/s', 'degF',
               'degR', 'degC', 'g0', 'lbf/in', 'turn', 'rpm', 'rps', 'kWh', 'bar', 'L', 'h', 'min', 't', 'km/h',
               'percent'}


def display_value(value, var):
    """Readable metric (value, unit) for an SI value: the suggested unit giving 1 ≤ |v| < 1000 (angles in deg)."""
    if value is None or var.structured or not isinstance(value, (int, float)):
        return None
    if var.unit == 'rad':
        return {'value': float(value) * 180 / math.pi, 'unit': 'deg'}
    if var.unit == '':
        return {'value': float(value), 'unit': ''}
    best = (var.unit, float(value))
    if value != 0:
        for u in suggestions(var.unit):
            if not u or u in _NON_METRIC or u == var.unit:
                continue
            try:
                v = float(Q_(value, unit_of(var.unit)).to(u).magnitude)
            except Exception:
                continue
            if 1 <= abs(v) < 1000 and not (1 <= abs(best[1]) < 1000):
                best = (u, v)
    return {'value': best[1], 'unit': best[0]}


def describe(calc_id):
    """Form schema for one calculator."""
    c = get(calc_id)
    return _clean({
        'id': c.id, 'title': c.title, 'section': c.section, 'kind': 'procedure' if c.procedure else 'equations',
        'outputs': c.outputs, 'n_equations': len(c.equations) if not c.procedure else None,
        'vars': [{'name': v.name, 'label': v.label or v.name, 'unit': v.unit, 'desc': v.desc,
                  'lo': v.bounds()[0], 'hi': v.bounds()[1], 'integer': v.integer,
                  'units': suggestions(v.unit), 'example': c.example.get(v.name), 'kind': v.kind,
                  'choices': v.choices,
                  'display': display_value(c.example.get(v.name), v),
                  'source': v.source} for v in c.vars],
        'equations': equation_text(c), 'assumptions': c.assumptions, 'refs': c.refs,
        'plots': [{'id': p['id'], 'title': p.get('title', p['id'])} for p in c.plots],
        'no_invert': c.no_invert,
    })


def catalog(query=None, section_key=None):
    """Sections with their calculators, optionally filtered by free-text query."""
    reg = registry()
    q = (query or '').lower().split()
    out = []
    for sk, sec in reg['sections'].items():
        if section_key and sk != section_key:
            continue
        items = []
        for c in reg['calcs'].values():
            if c.section != sk:
                continue
            hay = ' '.join([c.id, c.title, ' '.join(c.keywords), ' '.join(v.desc for v in c.vars)]).lower()
            if all(w in hay for w in q):
                items.append({'id': c.id, 'title': c.title,
                              'kind': 'procedure' if c.procedure else 'equations'})
        if items or not q:
            out.append({'key': sk, 'title': sec.title, 'summary': sec.summary, 'calcs': items})
    return {'version': MECHCALC_VERSION, 'sections': out, 'errors': reg['errors'],
            'counts': {'sections': len(reg['sections']), 'calcs': len(reg['calcs'])}}


def sweep(calc_id, inputs, var, start, stop, n=50, solve_for=None, log=False, out_units=None):
    """Vary one known input over [start, stop] and tabulate the unknowns; returns table + chart spec."""
    calc = get(calc_id)
    unknowns = list(solve_for or calc.outputs)
    if var in unknowns:
        raise MechError(f'{calc_id}: the swept variable {var} cannot also be an unknown')
    v = calc.var(var)
    a, b = to_si(start, v), to_si(stop, v)
    n = int(max(2, min(int(n), 400)))
    if log:
        if a <= 0 or b <= 0:
            raise MechError('log sweep needs positive start and stop')
        xs = np.logspace(math.log10(a), math.log10(b), n)
    else:
        xs = np.linspace(a, b, n)
    base = parse_inputs(calc, inputs, unknowns)
    rows, series = [], {u: [] for u in unknowns}
    xs_ok = []
    for x in xs:
        known = dict(base)
        known[var] = float(x)
        try:
            if calc.procedure is not None:
                sols, _ = run_procedure(calc, known, unknowns)
            else:
                sols, _ = solve_equations(calc, known, unknowns)
        except MechError:
            sols = []
        if not sols:
            continue
        s = sols[0]
        xs_ok.append(float(x))
        row = {var: float(x)}
        for u in unknowns:
            val = s.get(u)
            row[u] = val
            series[u].append(val)
        rows.append(row)
    out_units = out_units or {}
    xunit = out_units.get(var) or v.unit
    xdisp = [from_si(x, v, xunit)[0] for x in xs_ok]
    charts = []
    for u in unknowns:
        if not all(isinstance(y, (int, float)) for y in series[u]):
            continue
        uv = calc.var(u)
        yunit = out_units.get(u) or uv.unit
        charts.append({'title': f'{uv.label or u} vs {v.label or var}',
                       'xlabel': f'{v.label or var} [{xunit}]', 'ylabel': f'{uv.label or u} [{yunit}]',
                       'xlog': bool(log),
                       'series': [{'name': u, 'x': xdisp, 'y': [from_si(y, uv, yunit)[0] for y in series[u]]}]})
    return _clean({'calc': calc_id, 'var': var, 'unknowns': unknowns, 'rows': rows,
                   'skipped': int(n - len(rows)), 'charts': charts})


def plot(calc_id, inputs, plot_id, solve_for=None):
    """Named plot declared by the calculator: generic sweep spec or custom diagram function."""
    calc = get(calc_id)
    spec = next((p for p in calc.plots if p['id'] == plot_id), None)
    if spec is None:
        raise MechError(f'{calc_id}: no plot named {plot_id!r}')
    if 'fn' in spec:
        inputs = {**calc.example, **(inputs or {})}  # same example defaults as the generic sweep branch
        res = compute(calc_id, inputs, solve_for)
        vals = dict(parse_inputs(calc, inputs, res['unknowns']))
        for k, r in res['results'].items():
            if isinstance(r.get('value'), (int, float)) and k in calc.names:
                vals[k] = to_si({'value': r['value'], 'unit': r['unit']}, calc.var(k))
            else:
                vals[k] = r.get('value')
        charts = spec['fn'](vals)
        return _clean({'calc': calc_id, 'plot': plot_id, 'charts': charts if isinstance(charts, list) else [charts]})
    return sweep(calc_id, {**calc.example, **(inputs or {})}, spec['x'], spec['from'], spec['to'],
                 spec.get('n', 60), solve_for=spec.get('y'), log=spec.get('xlog', False))


